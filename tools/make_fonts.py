#!/usr/bin/env python3
"""Converts Inter into the clock's 1-bit GFX fonts: lib/ui/src/fonts.{h,cpp}.

    python3 tools/make_fonts.py [--ttc /usr/share/fonts/inter/Inter.ttc]

Each text font holds ASCII, the Ukrainian Cyrillic letters, '·', '©' and 'ʼ' (U+02BC; clock
strings use it for the apostrophe). Inter is under the SIL Open Font Licence 1.1.
"""

import argparse
import pathlib
import subprocess

from PIL import Image, ImageDraw, ImageFont

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "lib" / "ui" / "src"

TEXT_RANGES = [(0x20, 0x7E), (0xA9, 0xA9), (0xB7, 0xB7), (0x2BC, 0x2BC), (0x404, 0x404), (0x406, 0x407),
               (0x410, 0x44F), (0x454, 0x454), (0x456, 0x457), (0x490, 0x491)]
DIGIT_RANGES = [(0x2D, 0x3A)]  # "-./0123456789:"

# name, style, pixel size, ranges, what it is for
FONTS = [
    ("kInterTime", "Light", 66, DIGIT_RANGES, "clock digits"),
    ("kInterTitle", "SemiBold", 15, TEXT_RANGES, "pills and card titles"),
    ("kInterBody", "Regular", 13, TEXT_RANGES, "date and card details"),
    ("kInterSmall", "Medium", 10, TEXT_RANGES, "legend, credits, ring labels"),
]


def find_face(ttc: str, style: str) -> ImageFont.FreeTypeFont:
    for index in range(64):
        try:
            face = ImageFont.truetype(ttc, 20, index=index)
        except OSError:
            break
        family, name = face.getname()
        if family == "Inter" and name.replace(" ", "") == style:
            return ImageFont.truetype(ttc, 20, index=index), index
    raise SystemExit(f"Inter {style} not found in {ttc}")


def glyph(font: ImageFont.FreeTypeFont, code: int):
    ch = chr(code)
    advance = round(font.getlength(ch))
    x0, y0, x1, y1 = font.getbbox(ch, anchor="ls")
    width, height = max(0, x1 - x0), max(0, y1 - y0)
    if width == 0 or height == 0 or ch == " ":
        return [], 0, 0, advance, 0, 0
    image = Image.new("L", (width, height), 0)
    ImageDraw.Draw(image).text((-x0, -y0), ch, font=font, fill=255, anchor="ls")
    pixels = image.load()
    bits = [1 if pixels[x, y] >= 128 else 0 for y in range(height) for x in range(width)]
    return bits, width, height, advance, x0, y0


def pack(bits):
    out = []
    for i in range(0, len(bits), 8):
        chunk = bits[i:i + 8] + [0] * (8 - len(bits[i:i + 8]))
        out.append(sum(b << (7 - j) for j, b in enumerate(chunk)))
    return out


def convert(ttc, name, style, size, ranges):
    _, index = find_face(ttc, style)
    font = ImageFont.truetype(ttc, size, index=index)
    bitmap, glyphs = [], []
    for start, end in ranges:
        for code in range(start, end + 1):
            bits, width, height, advance, x_offset, y_offset = glyph(font, code)
            glyphs.append((len(bitmap), width, height, advance, x_offset, y_offset))
            bitmap += pack(bits)
    ascent, descent = font.getmetrics()
    lines = [f"// Inter {style} {size} px, {sum(e - s + 1 for s, e in ranges)} glyphs.",
             f"const uint8_t {name}Bitmap[] PROGMEM = {{"]
    for i in range(0, len(bitmap), 20):
        lines.append("  " + ", ".join(f"0x{b:02x}" for b in bitmap[i:i + 20]) + ",")
    lines.append("};")
    lines.append(f"const lgfx::GFXglyph {name}Glyphs[] PROGMEM = {{")
    for offset, width, height, advance, x_offset, y_offset in glyphs:
        lines.append(f"  {{{offset}, {width}, {height}, {advance}, {x_offset}, {y_offset}}},")
    lines.append("};")
    if len(ranges) > 1:
        lines.append(f"const lgfx::EncodeRange {name}Ranges[] PROGMEM = {{")
        base = 0
        for start, end in ranges:
            lines.append(f"  {{0x{start:04x}, 0x{end:04x}, {base}}},")
            base += end - start + 1
        lines.append("};")
        tail = f", {len(ranges)}, (lgfx::EncodeRange*){name}Ranges"
    else:
        tail = ""
    lines.append(f"const lgfx::GFXfont {name} PROGMEM = {{(uint8_t*){name}Bitmap, (lgfx::GFXglyph*){name}Glyphs, "
                 f"0x{ranges[0][0]:04x}, 0x{ranges[-1][1]:04x}, {ascent + descent}{tail}}};")
    return "\n".join(lines), len(bitmap) + 8 * len(glyphs)


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    default = subprocess.run(["fc-match", "-f", "%{file}", "Inter"], capture_output=True, text=True).stdout
    parser.add_argument("--ttc", default=default if default.endswith(".ttc") else "/usr/share/fonts/inter/Inter.ttc")
    args = parser.parse_args()
    header = ["#pragma once", "", "// Generated by tools/make_fonts.py from Inter (SIL OFL 1.1). Do not edit.", "",
              '#include "gfx.h"', "", "namespace ui {", ""]
    source = ["// Generated by tools/make_fonts.py from Inter (SIL OFL 1.1). Do not edit.", "",
              '#include "fonts.h"', "", '#include "flash.h"', "", "namespace ui {", ""]
    total = 0
    for name, style, size, ranges, purpose in FONTS:
        text, size_bytes = convert(args.ttc, name, style, size, ranges)
        total += size_bytes
        header.append(f"extern const lgfx::GFXfont {name};  // {purpose}")
        source += [text, ""]
    header += ["", "}  // namespace ui", ""]
    source += ["}  // namespace ui", ""]
    (OUT / "fonts.h").write_text("\n".join(header))
    (OUT / "fonts.cpp").write_text("\n".join(source))
    print(f"wrote {OUT / 'fonts.h'} and fonts.cpp, about {total} bytes of flash")


if __name__ == "__main__":
    main()
