#!/usr/bin/env python3
"""Writes test/wire_fixtures.h: messages encoded by the gateway's Python encoder,
for the C++ decoder's tests. gateway/tests checks the file is current, so a change to either
side of the protocol fails a test until both agree.

    python3 tools/make_wire_fixtures.py
"""

import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "gateway"))

from alert_gateway import wire  # noqa: E402

OUTPUT = ROOT / "test" / "wire_fixtures.h"
KEY = bytes(range(32))
NONCE = 0x1A2B3C4D


def snapshot(basemap_version):
    return wire.Snapshot(
        alert_level=wire.LEVEL_YELLOW, alerts_stale=False, threats_stale=True,
        alerts_age_s=12, threats_age_s=190, alert_duration_s=93784, basemap_version=basemap_version, px_per_km=4.0,
        rings_km=[10, 20], threats_in_watch=3, area_only_in_region=1, nearest_km=7.4,
        nearest_kind=wire.KINDS.index("missile"), nearest_heading=225, nearest_advisory=False,
        nearest_stale=True,
        markers=[
            wire.Marker(130, 95, 225, wire.KINDS.index("missile"), stale=True, uncertainty_px=0,
                        trail=[(160, 60), (150, 72), (140, 84)], anchor=(135, 90)),
            wire.Marker(-5, 250, -1, wire.KINDS.index("uav"), approximate=True, advisory=True,
                        uncertainty_px=40),
        ])


def basemap():
    palette = [0x18C6 + i for i in range(16)]
    rows = []
    for y in range(wire.SCREEN):
        if y == 120:
            rows.append(wire.encode_row([0] * 100 + [1] * 40 + [5] * 100))
        elif y == 121:  # short runs, one byte each, then a long one
            rows.append(wire.encode_row([2] * 7 + [15] * 1 + [3] * 15 + [4] * 217))
        else:
            rows.append(wire.encode_row([y % 3] * wire.SCREEN))
    return palette, rows


def c_array(name, data):
    lines = [f"constexpr uint8_t {name}[] = {{"]
    for i in range(0, len(data), 16):
        lines.append("    " + ", ".join(f"0x{b:02x}" for b in data[i:i + 16]) + ",")
    lines.append("};")
    return "\n".join(lines)


def render():
    palette, rows = basemap()
    version = wire.basemap_version(palette, rows)
    snapshot_message = wire.encode_snapshot(snapshot(version), NONCE, KEY)
    # The same picture announcing a basemap the clock does not have yet.
    new_map_message = wire.encode_snapshot(snapshot(version ^ 0xFFFF), NONCE, KEY)
    basemap_message = wire.encode_basemap(palette, rows, NONCE, KEY)
    return f"""#pragma once

// Generated by tools/make_wire_fixtures.py from the gateway's encoder. Do not edit.
// Key: bytes 0x00..0x1f. Nonce: 0x{NONCE:08x}. Basemap version: 0x{wire.basemap_version(palette, rows):08x}.

#include <cstdint>

namespace fixtures {{

constexpr uint32_t kNonce = 0x{NONCE:08x};
constexpr uint32_t kBasemapVersion = 0x{wire.basemap_version(palette, rows):08x};

{c_array("kSnapshot", snapshot_message)}

{c_array("kSnapshotNewBasemap", new_map_message)}

{c_array("kBasemap", basemap_message)}

}}  // namespace fixtures
"""


def main():
    OUTPUT.write_text(render())
    print(f"wrote {OUTPUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
